##Using SQL to filter, label and build features

SQL = """
CREATE OR REPLACE TABLE loans AS
SELECT
    CASE WHEN loan_status = 'Charged Off' THEN 1 ELSE 0 END                      AS default_flag,
    year(try_strptime(issue_d, '%b-%Y'))                                         AS issue_year,
    TRY_CAST(loan_amnt AS DOUBLE)                                                AS loan_amnt,
    CASE WHEN emp_length LIKE '<%' THEN 0
         ELSE TRY_CAST(regexp_extract(emp_length, '[0-9]+', 0) AS INTEGER) END   AS emp_length,
    TRY_CAST(annual_inc AS DOUBLE)                                               AS annual_inc,
    TRY_CAST(dti AS DOUBLE)                                                      AS dti,
    TRY_CAST(delinq_2yrs AS DOUBLE)                                              AS delinq_2yrs,
    TRY_CAST(inq_last_6mths AS DOUBLE)                                           AS inq_last_6mths,
    TRY_CAST(open_acc AS DOUBLE)                                                 AS open_acc,
    TRY_CAST(pub_rec AS DOUBLE)                                                  AS pub_rec,
    TRY_CAST(revol_bal AS DOUBLE)                                                AS revol_bal,
    TRY_CAST(REPLACE(revol_util, '%', '') AS DOUBLE)                             AS revol_util,
    TRY_CAST(total_acc AS DOUBLE)                                                AS total_acc,
    (TRY_CAST(fico_range_low AS DOUBLE) + TRY_CAST(fico_range_high AS DOUBLE)) / 2.0 AS fico_mid,
    year(try_strptime(issue_d, '%b-%Y')) - year(try_strptime(earliest_cr_line, '%b-%Y'))
                                                                                 AS credit_history_years,
    TRY_CAST(pub_rec_bankruptcies AS DOUBLE)                                     AS pub_rec_bankruptcies,
    home_ownership, verification_status, purpose,
    TRY_CAST(REPLACE(int_rate, '%', '') AS DOUBLE)                               AS int_rate_benchmark
FROM read_csv_auto('{path}', all_varchar = true, ignore_errors = true, sample_size = -1)
WHERE loan_status IN ('Fully Paid', 'Charged Off')   -- known outcomes only
  AND TRIM(term) = '36 months'                       -- 36m loans mostly resolved by end-2018
"""

def load(path):
    con = duckdb.connect()
    con.execute(SQL.format(path=path.replace("'", "''")))
    df = con.execute("SELECT * FROM loans WHERE issue_year IS NOT NULL").df()
    print(f"Loaded {len(df):,} resolved 36-month loans; default rate {df.default_flag.mean():.3%}")
    print(df.groupby("issue_year").default_flag.agg(["size", "mean"]).rename(
        columns={"size": "loans", "mean": "default_rate"}).to_string())
    return df


def add_features(df):
    df = df.copy()
    df["annual_inc_log"] = np.log1p(df["annual_inc"].clip(lower=0))
    df["revol_bal_log"] = np.log1p(df["revol_bal"].clip(lower=0))
    df["dti"] = df["dti"].clip(0, 60)                    # a few records have absurd values
    df["revol_util"] = df["revol_util"].clip(0, 150)
    for c in cat_cols:
        df[c] = df[c].fillna("missing").astype("category")  # same categories in every split
    return df

##Metrics

def ks_stat(y, p):
    fpr, tpr, _ = roc_curve(y, p)
    return float(np.max(tpr - fpr))


def score_block(y, p, is_probability=True):
    auc = roc_auc_score(y, p)
    out = {"auc": auc, "gini": 2 * auc - 1, "ks": ks_stat(y, p),
           "brier": brier_score_loss(y, p) if is_probability else np.nan,
           "default_rate": float(np.mean(y)),
           "mean_pred": float(np.mean(p)) if is_probability else np.nan, "n": int(len(y))}
    return out


def approval_table(y, p, name):
    order = np.argsort(p)
    y_sorted = np.asarray(y)[order]
    rows = []
    for rate in [1.0, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4]:
        k = int(len(y_sorted) * rate)
        rows.append({"model": name, "approval_rate": rate, "bad_rate_among_approved": y_sorted[:k].mean()})
    return pd.DataFrame(rows)


def psi(expected, actual, bins=10):
    """Population stability index using bins from the 'expected' (training) distribution."""
    expected = pd.Series(expected).dropna().to_numpy()
    actual = pd.Series(actual).dropna().to_numpy()
    edges = np.unique(np.quantile(expected, np.linspace(0, 1, bins + 1)))
    if len(edges) < 3:
        return np.nan
    edges[0], edges[-1] = -np.inf, np.inf
    e = np.histogram(expected, edges)[0] / len(expected)
    a = np.histogram(actual, edges)[0] / len(actual)
    e, a = np.clip(e, 1e-4, None), np.clip(a, 1e-4, None)
    return float(np.sum((a - e) * np.log(a / e)))


def psi_label(v):
    return "stable" if v < 0.10 else ("moderate shift" if v < 0.25 else "significant shift")

##Main code

def main(path):
    os.makedirs(out, exist_ok=True)
    df = add_features(load(path))

    train = df[df.issue_year.between(*train_years)]
    valid = df[df.issue_year == valid_year]
    test = df[df.issue_year == test_year]
    for name, part in [("train", train), ("valid", valid), ("test", test)]:
        if len(part) < 1000:
            sys.exit(f"Too few rows in {name} split ({len(part)}). Check the year settings.")
    feats = num_cols + cat_cols

    ##Model A: logistic regression (with interpretable baseline)
    pre = ColumnTransformer([
        ("num", Pipeline([("imp", SimpleImputer(strategy="median")), ("sc", StandardScaler())]), num_cols),
        ("cat", OneHotEncoder(handle_unknown="ignore"), cat_cols),
    ])
    lr = Pipeline([("pre", pre), ("clf", LogisticRegression(max_iter=1000, C=1.0))])
    lr.fit(train[feats], train.default_flag)

    ##Model B: gradient boosting
    gb = HistGradientBoostingClassifier(
        max_iter=300, learning_rate=0.05, max_leaf_nodes=15, l2_regularization=1.0,
        categorical_features="from_dtype", random_state=seed)
    gb.fit(train[feats], train.default_flag)

    models = {"logistic_regression": lr, "gradient_boosting": gb}
    rows, preds = [], {}
    for mname, m in models.items():
        for sname, part in [("train", train), ("valid", valid), ("test", test)]:
            p = m.predict_proba(part[feats])[:, 1]
            preds[(mname, sname)] = p
            rows.append({"model": mname, "split": sname, **score_block(part.default_flag.values, p)})
    ##Benchmark: the lender's own interest rate as a risk score
    for sname, part in [("valid", valid), ("test", test)]:
        b = part.dropna(subset=["int_rate_benchmark"])
        rows.append({"model": "lender_int_rate_benchmark", "split": sname,
                     **score_block(b.default_flag.values, b.int_rate_benchmark.values, is_probability=False)})
    metrics = pd.DataFrame(rows)
    metrics.to_csv(f"{out}/metrics.csv", index=False)
    print("\n=== Metrics (train 2010-13, valid 2014, test 2015) ===")
    print(metrics.round(4).to_string(index=False))

    ##Approval table on the test year
    appr = pd.concat([approval_table(test.default_flag.values, preds[(m, "test")], m) for m in models])
    appr.to_csv(f"{out}/approval_table_test.csv", index=False)
    print("\n=== Bad rate among approved, test year ===")
    print(appr.pivot(index="approval_rate", columns="model", values="bad_rate_among_approved")
          .round(4).sort_index(ascending=False).to_string())

    ##Calibration plot (test year)
    fig, ax = plt.subplots(figsize=(5, 5))
    for mname in models:
        frac, mean_p = calibration_curve(test.default_flag.values, preds[(mname, "test")],
                                         n_bins=10, strategy="quantile")
        ax.plot(mean_p, frac, marker="o", label=mname)
    lim = max(0.4, test.default_flag.mean() * 3)
    ax.plot([0, lim], [0, lim], "k--", lw=1, label="perfect calibration")
    ax.set_xlabel("Predicted default probability"); ax.set_ylabel("Observed default rate")
    ax.set_title(f"Calibration, test year {test_year}"); ax.legend(); fig.tight_layout()
    fig.savefig(f"{out}/calibration.png", dpi=150); plt.close(fig)

    ##Drift monitoring: PSI of score and features, train vs later years
    mon_rows = []
    best = "gradient_boosting"
    score_train = preds[(best, "train")]
    for sname, part in [("valid", valid), ("test", test)]:
        v = psi(score_train, preds[(best, sname)])
        mon_rows.append({"item": "model score", "compared_with": sname, "psi": v, "reading": psi_label(v)})
        for c in num_cols:
            v = psi(train[c], part[c])
            mon_rows.append({"item": c, "compared_with": sname, "psi": v, "reading": psi_label(v)})
    mon = pd.DataFrame(mon_rows)
    mon.to_csv(f"{out}/psi.csv", index=False)
    top = mon[mon.compared_with == "test"].sort_values("psi", ascending=False).head(10)
    print("\n=== Largest PSI, train vs test year ===")
    print(top.round(4).to_string(index=False))

    fig, ax = plt.subplots(figsize=(7, 4.5))
    top = top.iloc[::-1]
    ax.barh(top["item"], top["psi"])
    ax.axvline(0.10, color="k", ls="--", lw=1); ax.axvline(0.25, color="k", ls=":", lw=1)
    ax.set_xlabel("PSI vs training period (dashed 0.10, dotted 0.25)")
    ax.set_title(f"Largest shifts, {test_year}"); fig.tight_layout()
    fig.savefig(f"{out}/psi.png", dpi=150); plt.close(fig)

    ##Performance by issue year (model trained on <= 2013 only)
    by_year = []
    later = df[df.issue_year > train_years[1]]
    for y, part in later.groupby("issue_year"):
        if part.default_flag.nunique() < 2:
            continue
        by_year.append({"issue_year": int(y), "n": len(part), "default_rate": part.default_flag.mean(),
                        "auc_gb": roc_auc_score(part.default_flag, gb.predict_proba(part[feats])[:, 1]),
                        "auc_lr": roc_auc_score(part.default_flag, lr.predict_proba(part[feats])[:, 1])})
    pd.DataFrame(by_year).to_csv(f"{out}/performance_by_year.csv", index=False)
    print("\n=== AUC by issue year (trained on 2010-2013) ===\nNote: 36-month loans issued 2016+ are only partly resolved by the end of the data (2018Q4), so\ntheir outcomes are biased toward early defaults/prepayments. Treat 2016+ rows with caution.")
    print(pd.DataFrame(by_year).round(4).to_string(index=False))

    with open(f"{out}/run_info.json", "w") as f:
        json.dump({"seed": seed, "train_years": train_years, "valid_year": valid_year,
                   "test_year": test_year, "data_file": os.path.basename(path)}, f, indent=2)
    print(f"\nSaved tables and plots to {out}/")


